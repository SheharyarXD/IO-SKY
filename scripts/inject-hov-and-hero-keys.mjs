function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

let report = [];
for (const [loc, map] of Object.entries(HOV)) {
  const file = path.join(dir, loc + ".ts");
  let src = fs.readFileSync(file, "utf8");
  const lines = [];
  for (const [k, v] of Object.entries(map)) {
    if (src.includes(`"${k}"`)) continue;
    lines.push(`  "${k}": "${esc(v)}",`);
  }
  if (lines.length === 0) { report.push(`${loc}: nothing to add`); continue; }
  // Insert before the final closing brace of the exported object.
  const marker = src.lastIndexOf("};");
  if (marker === -1) { report.push(`${loc}: NO CLOSING BRACE`); continue; }
  src = src.slice(0, marker) + "\n  // Hero operational-intelligence mockup (hov.*)\n" + lines.join("\n") + "\n" + src.slice(marker);
  fs.writeFileSync(file, src, "utf8");
  report.push(`${loc}: added ${lines.length} keys`);
}
