function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

let total = 0;
for (const code of ALL) {
  const path = join(I18N_DIR, `${code}.ts`);
  let src = readFileSync(path, "utf8");
  const existing = new Set([...src.matchAll(/^\s*"([^"]+)"\s*:/gm)].map((m) => m[1]));

  const additions = [];
  for (const [id, byLocale] of Object.entries(Q)) {
    const key = `aiscan.q.${id}`;
    if (existing.has(key)) continue;
    additions.push(`  "${key}": "${esc(byLocale[code] ?? byLocale.en)}",`);
  }
  for (const [id, byLocale] of Object.entries(HELPERS)) {
    const key = `aiscan.q.${id}.helper`;
    if (existing.has(key)) continue;
    additions.push(`  "${key}": "${esc(byLocale[code] ?? byLocale.en)}",`);
  }
  if (additions.length === 0) {
    console.log(`${code}: nothing to add`);
    continue;
  }
  const lastBrace = src.lastIndexOf("};");
  src = src.slice(0, lastBrace) + additions.join("\n") + "\n" + src.slice(lastBrace);
  writeFileSync(path, src, "utf8");
  total += additions.length;
  console.log(`${code}: added ${additions.length} key(s)`);
}
console.log(`\nDone. Added ${total} aiscan.q.* key(s).`);
