def esc(v: str) -> str:
    return v.replace("\\", "\\\\").replace('"', '\\"')


def upsert(path: pathlib.Path, kv: dict):
    text = path.read_text(encoding="utf-8")
    for key, val in kv.items():
        line = f'  "{key}": "{esc(val)}",'
        # match existing key with possibly multi-line value up to the line ending with ",
        pat = re.compile(r'^[ \t]*"' + re.escape(key) + r'"\s*:\s*(?:"(?:[^"\\]|\\.)*"|\s*\n\s*"(?:[^"\\]|\\.)*")\s*,?[ \t]*$',
                         re.MULTILINE)
        if pat.search(text):
            text = pat.sub(line, text, count=1)
        else:
            # insert before final closing "};"
            idx = text.rfind("};")
            text = text[:idx] + line + "\n" + text[idx:]
    path.write_text(text, encoding="utf-8")


